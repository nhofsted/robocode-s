package io.github.nhofsted.robocodes.determinism;

import io.github.nhofsted.robocodes.determinism.WorkProfile.Group;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.MethodInsnNode;

import java.util.EnumMap;
import java.util.Map;

/**
 * What robot code's work costs, in counted units of {@link RobotRandomness#PICOS_PER_UNIT}
 * each (#15, ADR 0014, ADR 0018, ADR 0026): a price per kind of instruction ({@link Group}),
 * per call into the JDK (some methods priced on their own), per unit of a sized JDK call
 * ({@link JdkCosts}) and per element of a new array. Part of the deterministic rules (3).
 *
 * <p>Calibrated on 2026-11-01 against classic 1.11.1 on OpenJDK 21 (x86-64, WSL2): the real
 * CPU time of 1491 robots of the RoboRumble corpus, the heavy robots of the rumble and
 * benchmarks of one kind of work each (robots/testbots calib.*), fitted per kind
 * (tools/difftest/corpus/fit-costs.py), then scaled down (0.588) so that 95% of the robots
 * doing over 300 000 counted instructions a turn are charged no more than their real time:
 * a robot is rather given too much time than skips turns it wouldn't in classic. At least 1
 * unit an instruction, so that every loop costs something (the work cutoff ends endless ones).
 *
 * <p>Prices are fixed when a class is instrumented: a block's cost is one constant, so
 * prices cost nothing at run time.
 */
final class WorkPrices {

    /** Units of one instruction in rules 2, which counted every instruction alike at 160 ps. */
    static final long INSTRUCTION = 16;

    private static final Map<Group, Long> GROUPS = new EnumMap<>(Group.class);

    // Generated by tools/difftest/corpus/write-prices.py from the calibration of 2026-11-01
    // (1491 robots; generous scale 0.588).
    static {
        GROUPS.put(Group.ARRAY_LENGTH, 1L);
        GROUPS.put(Group.ARRAY_LOAD, 6L);
        GROUPS.put(Group.ARRAY_STORE, 12L);
        GROUPS.put(Group.BRANCH, 1L);
        GROUPS.put(Group.COMPARE, 22L);
        GROUPS.put(Group.CONST, 1L);
        GROUPS.put(Group.CONVERT, 11L);
        GROUPS.put(Group.FIELD_GET, 7L);
        GROUPS.put(Group.FIELD_PUT, 7L);
        GROUPS.put(Group.FLOAT, 10L);
        GROUPS.put(Group.FLOAT_DIV, 19L);
        GROUPS.put(Group.INT, 1L);
        GROUPS.put(Group.INT_MUL_DIV, 1L);
        GROUPS.put(Group.INVOKE, 12L);
        GROUPS.put(Group.INVOKE_INTERFACE, 9L);
        GROUPS.put(Group.JDK_CALL, 38L);
        GROUPS.put(Group.LOAD, 1L);
        GROUPS.put(Group.NEW, 9L);
        GROUPS.put(Group.NEW_ARRAY, 7L);
        GROUPS.put(Group.RETURN, 12L);
        GROUPS.put(Group.ROBOT_API, 7L);
        GROUPS.put(Group.STACK, 28L);
        GROUPS.put(Group.STATIC_GET, 1L);
        GROUPS.put(Group.STORE, 18L);
        GROUPS.put(Group.TYPE_CHECK, 12L);
        GROUPS.put(Group.OTHER, 7L);
    }
    /** A call into the JDK without a price of its own (the call instruction included). */
    private static final long JDK_CALL = 38;
    /** JDK methods with prices of their own ({@code owner.name desc}), the call included. */
    private static final Map<String, Long> JDK_METHODS = Map.ofEntries(
            Map.entry("java/lang/Math.acos(D)D", 149L),
            Map.entry("java/lang/Math.asin(D)D", 261L),
            Map.entry("java/lang/Math.atan(D)D", 387L),
            Map.entry("java/lang/Math.atan2(DD)D", 777L),
            Map.entry("java/lang/Math.cos(D)D", 1170L),
            Map.entry("java/lang/Math.exp(D)D", 598L),
            Map.entry("java/lang/Math.hypot(DD)D", 132L),
            Map.entry("java/lang/Math.log(D)D", 176L),
            Map.entry("java/lang/Math.pow(DD)D", 379L),
            Map.entry("java/lang/Math.sin(D)D", 1036L),
            Map.entry("java/lang/Math.sqrt(D)D", 158L),
            Map.entry("java/lang/Math.tan(D)D", 128L),
            Map.entry("java/lang/StrictMath.pow(DD)D", 119L),
            Map.entry("java/util/HashMap.containsKey(Ljava/lang/Object;)Z", 156L),
            Map.entry("java/util/HashMap.get(Ljava/lang/Object;)Ljava/lang/Object;", 422L),
            Map.entry("java/util/HashMap.put(Ljava/lang/Object;Ljava/lang/Object;)Ljava/lang/Object;", 112L),
            Map.entry("java/util/Hashtable.elements()Ljava/util/Enumeration;", 127L),
            Map.entry("java/util/Hashtable.get(Ljava/lang/Object;)Ljava/lang/Object;", 592L),
            Map.entry("java/util/Hashtable.values()Ljava/util/Collection;", 109L),
            Map.entry("java/util/Vector.add(Ljava/lang/Object;)Z", 120L),
            Map.entry("java/util/Vector.elementAt(I)Ljava/lang/Object;", 426L),
            Map.entry("java/util/Vector.get(I)Ljava/lang/Object;", 457L),
            Map.entry("java/util/Vector.size()I", 399L));
    /** Units per unit of size of sized JDK calls with prices of their own. */
    private static final Map<String, Long> SIZED = Map.ofEntries(
            Map.entry("[D.clone()Ljava/lang/Object;", 22L),
            Map.entry("java/lang/System.arraycopy(Ljava/lang/Object;ILjava/lang/Object;II)V", 7L),
            Map.entry("java/util/Arrays.sort([I)V", 9L),
            Map.entry("java/util/Vector.contains(Ljava/lang/Object;)Z", 7L));
    /** Units per instruction of rules 2's per-unit costs, for the other sized calls. */
    private static final long SIZED_PER_INSTRUCTION = 7;
    private static final long ARRAY_ELEMENT = 31;
    private static final long REFERENCE_ARRAY_ELEMENT = 31;

    private WorkPrices() {
    }

    /** The price of one instruction; {@code jdk}: a call into the JDK. */
    static long of(AbstractInsnNode insn, boolean jdk) {
        if (jdk && insn instanceof MethodInsnNode call) {
            return JDK_METHODS.getOrDefault(call.owner + "." + call.name + call.desc, JDK_CALL);
        }
        return GROUPS.getOrDefault(WorkProfile.group(insn, jdk), GROUPS.get(Group.OTHER));
    }

    /**
     * Units per unit of size of the sized JDK call {@code method} ({@code owner.name desc}),
     * which rules 2 priced at {@code instructions} per unit.
     */
    static long sized(String method, long instructions) {
        Long own = SIZED.get(method);
        return own != null ? own : instructions * SIZED_PER_INSTRUCTION;
    }

    /** Units per element of a new array ({@code newarray}: primitive; {@code anewarray}). */
    static long arrayElement(boolean primitive) {
        return primitive ? ARRAY_ELEMENT : REFERENCE_ARRAY_ELEMENT;
    }
}

# The Homebrew tap of robocode-s (design §6.9, issue #79): a GitHub repository
# nhofsted/homebrew-robocode-s with Casks/robocode-s.rb, for
#   brew install --cask nhofsted/robocode-s/robocode-s
#
#   tools/release/tap.sh VERSION [--for-real]
#
# Prepares the tap as a local git checkout in target/homebrew-tap (the cask of
# `release.sh cask VERSION`, a README) and prints the commands that publish it. Without
# --for-real nothing leaves this machine; with it, the commit is made and pushed, and the
# GitHub repository is created on the first time (`gh repo create`, public).
# The GitHub release vVERSION (the .app.zip files the cask downloads) must exist first.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TAP_REPO=nhofsted/homebrew-robocode-s
version="${1:?usage: tap.sh VERSION [--for-real]}"
real=0
[ "${2:-}" = --for-real ] && real=1
tap="$ROOT/target/homebrew-tap"

# Once the tap exists, a fresh checkout starts from its history (a push needs it).
if [ ! -d "$tap/.git" ] && gh repo view "$TAP_REPO" >/dev/null 2>&1; then
  rm -rf "$tap"
  gh repo clone "$TAP_REPO" "$tap" -- -q
fi
mkdir -p "$tap/Casks"
"$ROOT/tools/release/release.sh" cask "$version" > "$tap/Casks/robocode-s.rb"
cat > "$tap/README.md" <<'EOF'
# homebrew-robocode-s

Homebrew tap of [robocode-s](https://github.com/nhofsted/robocode-s), a Robocode battle engine and viewer (macOS).

```sh
brew install --cask nhofsted/robocode-s/robocode-s
```

The app is not signed or notarized; the cask removes the quarantine attribute so that Gatekeeper opens it.
Update with `brew upgrade --cask robocode-s`. This repository is generated by `tools/release/tap.sh` in the main repository.
EOF
[ -d "$tap/.git" ] || git -C "$tap" init -q -b main
# The commit is the main repository's author's (a global identity may not exist).
for key in user.name user.email; do
  git -C "$tap" config "$key" >/dev/null || git -C "$tap" config "$key" "$(git -C "$ROOT" config "$key")"
done
echo "prepared $tap:" >&2
ls -R "$tap/Casks" "$tap/README.md" >&2

cmds=(
  "git -C $tap add -A"
  "git -C $tap commit -m 'robocode-s $version'"
)
if git -C "$tap" remote get-url origin >/dev/null 2>&1; then
  cmds+=("git -C $tap push origin main")
else
  cmds+=("gh repo create $TAP_REPO --public --description 'Homebrew tap of robocode-s' --source $tap --remote origin --push")
fi
if [ $real = 1 ]; then
  git -C "$tap" add -A
  git -C "$tap" commit -q -m "robocode-s $version" || echo "nothing new to commit" >&2
  if git -C "$tap" remote get-url origin >/dev/null 2>&1; then
    git -C "$tap" push origin main
  else
    gh repo create "$TAP_REPO" --public --description "Homebrew tap of robocode-s" --source "$tap" --remote origin --push
  fi
else
  echo "DRY RUN: to publish, run (or use --for-real):" >&2
  printf '  %s\n' "${cmds[@]}"
fi

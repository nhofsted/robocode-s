"""Writes the work meter's prices (WorkPrices.java's table) from a fit (#15).

  write-prices.py <fit-costs log> <fit-costs --json> [--min-calls N] > table.java

Prices in units of RobotRandomness.PICOS_PER_UNIT (10 ps), the fit's scaled prices rounded,
at least 1 unit an instruction (so that every loop costs something: the work cutoff ends
endless loops). A JDK method gets a price of its own only with --min-calls calls in the
samples (others: the shared JDK call price); sized calls without one keep rules 2's relative
weights, scaled to the price of an element of System.arraycopy.
"""
import json, re, sys

UNIT_PS = 10


def main():
    log, prices_path = sys.argv[1], sys.argv[2]
    min_calls = float(sys.argv[sys.argv.index("--min-calls") + 1]) if "--min-calls" in sys.argv else 1e7
    prices = json.load(open(prices_path))["psPerUnit"]
    support = {}
    for line in open(log):
        m = re.match(r"\s+(\S.*?)\s+[-\d.]+ ps\s+\(([\d.e+]+) in all samples\)", line)
        if m:
            support[m.group(1)] = float(m.group(2))

    def units(ps, floor=1):
        return max(floor, round(ps / UNIT_PS))

    groups = {k: units(v) for k, v in prices.items() if not k.startswith(("jdk:", "sized", "alloc:")) and k != "other"}
    other = units(prices.get("other", 100))
    methods = {k[4:]: units(v) for k, v in prices.items()
               if k.startswith("jdk:") and support.get(k, 0) >= min_calls}
    sized = {k[6:]: units(v) for k, v in prices.items() if k.startswith("sized:")}
    copy = sized.get("java/lang/System.arraycopy(Ljava/lang/Object;ILjava/lang/Object;II)V", units(prices["sized_other"]))
    alloc = units(prices.get("alloc:primitive", 0), 0)
    alloc_ref = units(prices.get("alloc:reference", prices.get("alloc:primitive", 0)), 0)
    out = []
    out.append("    // Generated by tools/difftest/corpus/write-prices.py from the calibration of 2026-11-01")
    out.append(f"    // ({json.load(open(prices_path))['robots']} robots; generous scale "
               f"{json.load(open(prices_path))['scale']:.3f}).")
    out.append("    static {")
    for g, u in sorted(groups.items()):
        out.append(f"        GROUPS.put(Group.{g.upper()}, {u}L);")
    out.append(f"        GROUPS.put(Group.OTHER, {other}L);")
    out.append("    }")
    out.append(f"    /** A call into the JDK without a price of its own (the call instruction included). */")
    out.append(f"    private static final long JDK_CALL = {groups.get('jdk_call', 38)};")
    out.append("    /** JDK methods with prices of their own ({@code owner.name desc}), the call included. */")
    out.append("    private static final Map<String, Long> JDK_METHODS = Map.ofEntries(")
    out.append(",\n".join(f'            Map.entry("{k}", {v}L)' for k, v in sorted(methods.items())) + ");")
    out.append("    /** Units per unit of size of sized JDK calls with prices of their own. */")
    out.append("    private static final Map<String, Long> SIZED = Map.ofEntries(")
    out.append(",\n".join(f'            Map.entry("{k}", {v}L)' for k, v in sorted(sized.items())) + ");")
    out.append("    /** Units per instruction of rules 2's per-unit costs, for the other sized calls. */")
    out.append(f"    private static final long SIZED_PER_INSTRUCTION = {copy};")
    out.append(f"    private static final long ARRAY_ELEMENT = {alloc};")
    out.append(f"    private static final long REFERENCE_ARRAY_ELEMENT = {alloc_ref};")
    print("\n".join(out))


if __name__ == "__main__":
    main()

// Writes src/lib/llm/logos.ts from LobeHub Icons. Usage, from web/:
//
//   npm pack @lobehub/icons-static-svg@1.101.0 && tar xzf lobehub-icons-static-svg-1.101.0.tgz
//   node scripts/gen-llm-logos.mjs package/icons
//
// Each vendor gets its coloured mark (`<slug>-color.svg`) where LobeHub has one, else its
// monochrome mark, which the badge draws in the text colour. A new vendor also needs a rule
// in src/lib/llm/vendors.ts.

import fs from 'node:fs';
import path from 'node:path';

const VERSION = '1.101.0';

/** Vendor key → LobeHub slug. */
const VENDORS = {
	claude: 'claude',
	openai: 'openai',
	gemini: 'gemini',
	gemma: 'gemma',
	grok: 'grok',
	deepseek: 'deepseek',
	mistral: 'mistral',
	qwen: 'qwen',
	meta: 'meta',
	kimi: 'kimi',
	zhipu: 'zhipu',
	minimax: 'minimax',
	microsoft: 'microsoft',
	nova: 'nova',
	cohere: 'cohere',
	nvidia: 'nvidia',
	ibm: 'ibm',
	wenxin: 'wenxin',
	hunyuan: 'hunyuan',
	doubao: 'doubao',
	perplexity: 'perplexity',
	githubcopilot: 'githubcopilot',
	copilot: 'copilot'
};

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/gen-llm-logos.mjs <@lobehub/icons-static-svg>/icons');

const entries = Object.entries(VENDORS).map(([key, slug]) => {
	const colourFile = path.join(dir, `${slug}-color.svg`);
	const colour = fs.existsSync(colourFile);
	const svg = fs.readFileSync(colour ? colourFile : path.join(dir, `${slug}.svg`), 'utf8');
	const [, root, inner] = svg.match(/^<svg([^>]*)>([\s\S]*)<\/svg>\s*$/) ?? [];
	if (inner === undefined) throw new Error(`${slug}: not a plain <svg>`);
	const name = inner.match(/<title>([^<]*)<\/title>/)?.[1] ?? slug;
	// Gradient and mask ids: stable and per vendor; the badge makes them unique per badge.
	const ids = [...inner.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
	let body = inner.replace(/<title>[^<]*<\/title>/, '');
	ids.forEach((id, i) => {
		body = body.replaceAll(`"${id}"`, `"llm-${key}-${i}"`).replaceAll(`#${id})`, `#llm-${key}-${i})`);
	});
	return { key, name, colour, evenodd: /fill-rule="evenodd"/.test(root), body };
});

const out = `// SPDX-License-Identifier: EPL-2.0

// Generated by scripts/gen-llm-logos.mjs from LobeHub Icons (@lobehub/icons-static-svg
// ${VERSION}, MIT, https://lobehub.com/icons): each vendor's coloured mark where LobeHub has
// one, else its monochrome mark (drawn in the text colour), on a 24x24 view box. The logos
// are their owners' trademarks, shown only to name the model a bot's author declared
// (\`robot.llm.model\`).

export interface VendorLogo {
	name: string;
	/** False for a monochrome mark, which takes the text colour. */
	colour: boolean;
	/** The SVG's fill-rule is even-odd. */
	evenodd: boolean;
	/** The SVG's content; its ids all start with \`llm-<vendor>-\`. */
	body: string;
}

const logos = {
${entries
	.map(
		(e) =>
			`\t${e.key}: {\n\t\tname: ${JSON.stringify(e.name)},\n\t\tcolour: ${e.colour},\n\t\tevenodd: ${e.evenodd},\n\t\tbody: ${JSON.stringify(e.body)}\n\t}`
	)
	.join(',\n')}
} satisfies Record<string, VendorLogo>;

export type Vendor = keyof typeof logos;

export const LOGOS: Record<Vendor, VendorLogo> = logos;
`;
fs.writeFileSync(new URL('../src/lib/llm/logos.ts', import.meta.url), out);
console.log(entries.map((e) => `${e.key}${e.colour ? '' : ' (mono)'}`).join(', '));
